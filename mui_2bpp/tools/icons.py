"""
icons.py: a C header with the icons of Material Symbols by name, from its
codepoints file:

  #define ICON_BATTERY_FULL "\\ue1a5"

A string literal per icon, drawn with u8g2_DrawUTF8(); cstrings.py reads
the header as any other source, so the icons go into the font like the
characters of the menus.

usage: icons.py -o icons.h codepoints name ...
"""

import argparse
import os
import sys


def main():
    ap = argparse.ArgumentParser(description="C header of Material Symbols icons")
    ap.add_argument("-o", required=True, metavar="icons.h", help="output")
    ap.add_argument("codepoints", help="name and hex code point per line")
    ap.add_argument("names", nargs="+", help="icon names, e.g. battery_full")
    a = ap.parse_args()

    with open(a.codepoints) as f:
        cp = dict(line.split() for line in f if line.strip())
    missing = [n for n in a.names if n not in cp]
    if missing:
        sys.exit("icons.py: not in " + a.codepoints + ": " + " ".join(missing))
    big = [n for n in a.names if int(cp[n], 16) > 0xFFFF]
    if big:
        sys.exit("icons.py: beyond 16 bits: " + " ".join(big))

    guard = os.path.basename(a.o).upper().replace(".", "_")
    with open(a.o, "w") as f:
        f.write(f"/* generated by icons.py from {os.path.basename(a.codepoints)} */\n\n")
        f.write(f"#ifndef {guard}\n#define {guard}\n\n")
        for n in a.names:
            f.write(f'#define ICON_{n.upper()} "\\u{int(cp[n], 16):04x}"\n')
        f.write("\n#endif\n")


if __name__ == "__main__":
    main()
